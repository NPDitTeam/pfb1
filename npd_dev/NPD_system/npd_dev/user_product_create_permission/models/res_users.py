#
#    คำอธิบาย:
#    ---------
#    โมเดลนี้ทำการ inherit (สืบทอด) จากโมเดล res.users ของ Odoo
#    และเพิ่มฟิลด์ Boolean ใหม่ชื่อ can_create_product
#    
#    การทำงาน:
#    ---------
#    1. ใช้ _inherit เพื่อสืบทอดโมเดล res.users
#    2. เพิ่มฟิลด์ Boolean ที่มีค่าเริ่มต้นเป็น False
#    3. ฟิลด์นี้จะแสดงในแถบ "สิทธิ์การเข้าใช้งาน" ของหน้าผู้ใช้งาน
#
#    หมายเหตุ:
#    ---------
#    - ฟิลด์นี้เป็นเพียง checkbox สำหรับเลือกติ๊กเท่านั้น
#    - ยังไม่มีการควบคุมสิทธิ์จริง (ต้องเขียน logic เพิ่มเติมภายหลัง)
#    - ไม่กระทบกับส่วนงานอื่นๆ ของระบบ
#
##############################################################################

from odoo import models, fields, api


class ResUsers(models.Model):
    """
    สืบทอดโมเดล res.users เพื่อเพิ่มฟิลด์ "สามารถสร้างสินค้าได้"
    
    โมเดล res.users คือโมเดลหลักที่เก็บข้อมูลผู้ใช้งานในระบบ Odoo
    การใช้ _inherit จะทำให้เราสามารถเพิ่มฟิลด์ใหม่โดยไม่ต้องแก้ไขโค้ดต้นฉบับ
    """
    
    # ระบุว่าจะสืบทอดจากโมเดลใด
    _inherit = 'res.users'
    
    # เพิ่มฟิลด์ใหม่: สามารถสร้างสินค้าได้
    # ชนิด: Boolean (checkbox - ติ๊กได้/ไม่ติ๊ก)
    # ค่าเริ่มต้น: False (ไม่ติ๊ก)
    can_create_product = fields.Boolean(
        string='สามารถสร้างสินค้าได้',  # ชื่อที่แสดงใน UI
        default=False,  # ค่าเริ่มต้นเป็น False (ไม่ติ๊ก)
        help='ติ๊กเพื่ออนุญาตให้ผู้ใช้งานสามารถสร้างสินค้าใหม่ได้',  # คำอธิบายเมื่อ hover
    )
